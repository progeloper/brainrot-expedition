// Voxel V4 exporter: design build (JS, design units, nose = +x) -> species data module
// src/shared/Config/VoxelCreatures/<ID>.lua. It only serialises boxes; the Luau
// VoxelCreatureBuilder is the only code that creates creature instances.
//
// Usage: node export_lua.js builds/<ID>.js <ID> <irisFamily> [overrides.json]
const fs = require('fs');
const path = require('path');
const [, , buildFile, id, irisFamily, overridesFile] = process.argv;
if (!buildFile || !id || !irisFamily) {
	console.error('usage: node export_lua.js builds/<ID>.js <ID> <irisFamily> [overrides.json]');
	process.exit(2);
}
const build = require(path.resolve(buildFile));
const { planRig } = require('./rig.js');
const rig = planRig(build.parts, build.rigOverrides);
const overrides = overridesFile ? JSON.parse(fs.readFileSync(overridesFile, 'utf8')) : {};
const ROLES = ['upper', 'lower', 'stripe', 'trim', 'skin', 'skin2', 'feather', 'feather2', 'foot', 'prop', 'accent'];
const MUTATIONS = { shiny: 'Shiny', golden: 'Golden', glitched: 'Glitched', radioactive: 'Radioactive', astral: 'Astral' };
const n = (v) => {
	const r = Math.round(v * 10000) / 10000;
	return Object.is(r, -0) ? '0' : String(r);
};
const hex = (c) => '#' + c.replace('#', '').toUpperCase();
const v3 = (a) => `{ ${a.map(n).join(', ')} }`;

let lo = [Infinity, Infinity, Infinity], hi = [-Infinity, -Infinity, -Infinity];
for (const p of build.parts) for (let i = 0; i < 3; i++) { lo[i] = Math.min(lo[i], p.min[i]); hi[i] = Math.max(hi[i], p.max[i]); }
const centreOf = (slots) => {
	const s = build.parts.filter((p) => slots.includes(p.slot));
	if (s.length === 0) return null;
	let a = [Infinity, Infinity, Infinity], b = [-Infinity, -Infinity, -Infinity];
	for (const p of s) for (let i = 0; i < 3; i++) { a[i] = Math.min(a[i], p.min[i]); b[i] = Math.max(b[i], p.max[i]); }
	return { lo: a, hi: b, c: a.map((v, i) => (v + b[i]) / 2) };
};
const ground = [(lo[0] + hi[0]) / 2, 0, (lo[2] + hi[2]) / 2];
const head = centreOf(['Head']) || centreOf(['EyeWhite']);
const mouth = centreOf(['Mouth', 'Beak']) || head;
let body = null, bodyVolume = -1;
for (const p of build.parts) {
	if (p.role !== 'upper') continue;
	const v = (p.max[0] - p.min[0]) * (p.max[1] - p.min[1]) * (p.max[2] - p.min[2]);
	if (v > bodyVolume) { bodyVolume = v; body = p; }
}
const anchors = {
	HeadTop: [head.c[0], hi[1], head.c[2]], // top of the whole silhouette (nametag anchor)
	CarryGrip: [(body.min[0] + body.max[0]) / 2, body.max[1], (body.min[2] + body.max[2]) / 2],
	CargoSeat: ground,
	BankDisplay: ground,
	FrontTeamMount: ground,
	Mouth: mouth.c,
	FxCore: lo.map((v, i) => (v + hi[i]) / 2),
};

const usedRoles = new Set(build.parts.filter((p) => p.role !== 'P').map((p) => p.role));
const pal = build.PALETTES.normal;
let out = [];
out.push('--!strict');
out.push(`-- Voxel V4 species data for ${id}. Generated by tools/voxel_v4/export_lua.js from`);
out.push(`-- tools/voxel_v4/${path.relative(path.resolve(__dirname), path.resolve(buildFile))}. Design units, y up, nose = +x.`);
out.push('-- Do not hand-edit geometry; edit the design build and re-export.');
out.push('return table.freeze({');
out.push(`\tid = "${id}",`);
out.push('\tversion = 4,');
out.push(`\tdesignHeight = ${n(hi[1] - lo[1])},`);
out.push(`\tirisFamily = "${irisFamily}",`);
// Optional giant species: gameplay height = the shared target height x sizeMultiplier (owner, 5 Nov 2026).
if (typeof build.sizeMultiplier === 'number' && build.sizeMultiplier !== 1) out.push(`\tsizeMultiplier = ${n(build.sizeMultiplier)},`);
out.push('\tpalette = table.freeze({');
for (const r of ROLES) if (usedRoles.has(r) && pal[r]) out.push(`\t\t${r} = "${hex(pal[r])}",`);
out.push('\t}),');
out.push('\tmutationOverrides = table.freeze({');
for (const m of Object.values(MUTATIONS)) {
	const o = overrides[m] || {};
	const keys = Object.keys(o);
	out.push(`\t\t${m} = table.freeze({${keys.map((k) => ` ${k} = "${hex(o[k])}"`).join(',')}${keys.length ? ' ' : ''}}),`);
}
out.push('\t}),');
out.push('\tanchors = table.freeze({');
for (const [k, v] of Object.entries(anchors)) out.push(`\t\t${k} = ${v3(v)},`);
out.push('\t}),');
if (Array.isArray(build.passiveFx) && build.passiveFx.length) {
	out.push('\tpassiveFx = table.freeze({');
	for (const f of build.passiveFx) {
		const pair = (a) => `{ ${n(a[0])}, ${n(a[1])} }`;
		out.push(`\t\t{ name = "${f.name}", texture = "${f.texture}", anchor = ${v3(f.anchor)}, rate = ${n(f.rate)}, lifetime = ${pair(f.lifetime)}, size = ${pair(f.size)}, transparency = ${pair(f.transparency)}, colors = { "${hex(f.colors[0])}", "${hex(f.colors[1])}" }, lightEmission = ${n(f.lightEmission || 0)}, speed = ${pair(f.speed)}, spread = ${n(f.spread)}, rise = ${n(f.rise || 0)} },`);
	}
	out.push('\t}),');
}
// Motor6D rig plan (tools/voxel_v4/rig.js): bones in parent-first order, pivots in design units.
out.push('\trig = table.freeze({');
for (const b of rig.bones) out.push(`\t\t{ name = "${b.name}", parent = "${b.parent}", pivot = ${v3(b.pivot)} },`);
out.push('\t}),');
out.push('\tboxes = table.freeze({');
for (const p of build.parts) {
	const role = p.role === 'P' ? 'Protected' : p.role;
	const fields = [
		`slot = "${p.slot}"`,
		`min = ${v3(p.min)}`,
		`max = ${v3(p.max)}`,
		`role = "${role}"`,
		`relief = ${(p.flags & 1) !== 0}`,
		`emissive = ${(p.flags & 4) !== 0}`,
	];
	if (p.role === 'P') fields.push(`color = "${hex(p.col)}"`);
	fields.push(`bone = "${rig.bone[build.parts.indexOf(p)]}"`);
	out.push(`\t\t{ ${fields.join(', ')} },`);
}
out.push('\t}),');
out.push('})');
const target = path.resolve(__dirname, '../../src/shared/Config/VoxelCreatures', `${id}.lua`);
fs.writeFileSync(target, out.join('\n') + '\n');
console.log(JSON.stringify({ id, boxes: build.parts.length, target, bounds: { lo, hi }, roles: [...usedRoles] }));
