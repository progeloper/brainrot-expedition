def wedge(cx, cz, width, rise, run, facing):
    """Ramp from ground up to `rise`; `facing` = direction of travel UP the ramp (N/S/E/W).
    A Roblox wedge is tallest at local +Z, so yaw maps local +Z onto the uphill direction."""
    yaw = {"N": 180, "S": 0, "E": 90, "W": -90}[facing]
    top = FILL(rise)
    return {"cframe": f"@CFrame.new({n(cx)}, {n((G + top) / 2)}, {n(cz)}) * CFrame.Angles(0, math.rad({n(yaw)}), 0)",
            "size": [width, top - G, run], "material": "LeafyGrass"}


