def n(v):
    v = round(v, 3)
    return str(int(v)) if float(v).is_integer() else repr(v)


def lua(value, indent=0):
    pad = "\t" * indent
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return n(value)
    if isinstance(value, str):
        if value.startswith("@"):  # raw Luau expression
            return value[1:]
        return '"' + value.replace('"', '\\"') + '"'
    if isinstance(value, (list, tuple)):
        if all(isinstance(x, (int, float)) for x in value) and len(value) <= 4:
            return "{ " + ", ".join(n(x) for x in value) + " }"
        inner = ",\n".join(pad + "\t" + lua(x, indent + 1) for x in value)
        return "{\n" + inner + ",\n" + pad + "}" if value else "{}"
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = []
        for k in value:  # insertion order = deterministic
            key = k if k.isidentifier() else '["' + k + '"]'
            items.append(pad + "\t" + key + " = " + lua(value[k], indent + 1))
        return "{\n" + ",\n".join(items) + ",\n" + pad + "}"
    raise TypeError(value)


def box(slot, x0, y0, z0, x1, y1, z1, role, relief=False, emissive=False, walkable=False, rot=None):
    b = {"slot": slot, "min": [min(x0, x1), min(y0, y1), min(z0, z1)], "max": [max(x0, x1), max(y0, y1), max(z0, z1)], "role": role}
    if relief:
        b["relief"] = relief if isinstance(relief, list) else True
    if emissive:
        b["emissive"] = True
    if walkable:
        b["walkable"] = True
    if rot:
        b["rot"] = list(rot)
    return b


