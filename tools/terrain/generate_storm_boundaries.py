#!/usr/bin/env python3
"""Generate src/shared/Config/StormBoundaries.lua from the authored region floor footprints.

Each locked region's polygon is the rectilinear outline of the union of its floor
rectangles (XZ plane). Deterministic: same input JSON -> byte-identical output.
Usage: python3 -I tools/terrain/generate_storm_boundaries.py
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "tools", "terrain", "region_floors.json")
OUT = os.path.join(ROOT, "src", "shared", "Config", "StormBoundaries.lua")
LOCKED = ["Beach", "Swamp", "Jungle", "Arctic", "Volcano", "GlitchZone"]
HEIGHT = 140  # visual curtain height only


def outline(rects):
    xs = sorted({v for cx, cz, sx, sz in rects for v in (cx - sx / 2, cx + sx / 2)})
    zs = sorted({v for cx, cz, sx, sz in rects for v in (cz - sz / 2, cz + sz / 2)})

    def inside(i, j):
        if i < 0 or j < 0 or i >= len(xs) - 1 or j >= len(zs) - 1:
            return False
        mx, mz = (xs[i] + xs[i + 1]) / 2, (zs[j] + zs[j + 1]) / 2
        return any(abs(mx - cx) < sx / 2 and abs(mz - cz) < sz / 2 for cx, cz, sx, sz in rects)

    edges = {}
    # Directed boundary edges with the interior on the left (counter-clockwise in x/z).
    for i in range(len(xs) - 1):
        for j in range(len(zs) - 1):
            if not inside(i, j):
                continue
            x0, x1, z0, z1 = xs[i], xs[i + 1], zs[j], zs[j + 1]
            if not inside(i, j - 1):
                edges[(x0, z0)] = (x1, z0)
            if not inside(i + 1, j):
                edges[(x1, z0)] = (x1, z1)
            if not inside(i, j + 1):
                edges[(x1, z1)] = (x0, z1)
            if not inside(i - 1, j):
                edges[(x0, z1)] = (x0, z0)
    start = min(edges)
    loop, cur = [start], edges[start]
    while cur != start:
        loop.append(cur)
        cur = edges[cur]
    if len(loop) != len(edges):
        sys.exit("region outline is not a single loop")
    # Drop collinear vertices.
    out = []
    n = len(loop)
    for k in range(n):
        a, b, c = loop[k - 1], loop[k], loop[(k + 1) % n]
        if (b[0] - a[0]) * (c[1] - b[1]) - (b[1] - a[1]) * (c[0] - b[0]) != 0:
            out.append(b)
    return out


def num(v):
    return str(int(v)) if float(v).is_integer() else repr(v)


def main():
    data = json.load(open(SRC))
    lines = [
        "--!strict",
        "-- GENERATED by tools/terrain/generate_storm_boundaries.py from tools/terrain/region_floors.json.",
        "-- Do not edit by hand. Locked-region footprints in XZ (Vector2.X = world X, Vector2.Y = world Z).",
        "-- Height is visual only; access is decided by the existing server guard.",
        "return table.freeze({",
    ]
    for key in LOCKED:
        pts = outline(data[key])
        body = ", ".join(f"Vector2.new({num(x)}, {num(z)})" for x, z in pts)
        lines.append(f"\t{key} = table.freeze({{ points = table.freeze({{ {body} }}), height = {HEIGHT} }}),")
    lines.append("})")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    # Every region (client atmosphere / POI lookups); same outline algorithm.
    out2 = os.path.join(ROOT, "src", "shared", "Config", "RegionFootprints.lua")
    lines = [
        "--!strict",
        "-- GENERATED by tools/terrain/generate_storm_boundaries.py from tools/terrain/region_floors.json.",
        "-- Every region's floor footprint in XZ (presentation lookups only; the server keeps its own floors).",
        "return table.freeze({",
    ]
    for key in [k for k in data if not k.startswith("_")]:
        pts = outline(data[key])
        body = ", ".join(f"Vector2.new({num(x)}, {num(z)})" for x, z in pts)
        lines.append(f"\t{key} = table.freeze({{ {body} }}),")
    lines.append("})")
    open(out2, "w").write("\n".join(lines) + "\n")
    print(f"wrote {out2}")


if __name__ == "__main__":
    main()
