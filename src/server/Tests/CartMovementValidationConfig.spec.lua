--!strict

return function()
	local ReplicatedStorage = game:GetService("ReplicatedStorage")

	local CartMovementValidation = require(ReplicatedStorage.Shared.Config.CartMovementValidation)

	describe("CartMovementValidation configuration", function()
		it("centralises the Phase 1Q Development safety tuning", function()
			local development = CartMovementValidation.Development

			expect(CartMovementValidation.Enabled).to.equal(true)
			expect(development.SampleInterval).to.equal(0.15)
			expect(development.ForwardSpeedMultiplier).to.equal(1.35)
			expect(development.ForwardSpeedAdditive).to.equal(10)
			expect(development.ReverseSpeedMultiplier).to.equal(2.5)
			expect(development.ReverseSpeedAdditive).to.equal(12)
			expect(development.LateralSpeedMultiplier).to.equal(1.5)
			expect(development.LateralSpeedAdditive).to.equal(14)
			expect(development.OverallSpeedMultiplier).to.equal(1.75)
			expect(development.OverallSpeedAdditive).to.equal(18)
			expect(development.CorrectiveHorizontalSpeedMultiplier).to.equal(2.25)
			expect(development.CorrectiveHorizontalSpeedAdditive).to.equal(24)
			expect(development.SevereHorizontalSpeedMultiplier).to.equal(3)
			expect(development.SevereHorizontalSpeedAdditive).to.equal(30)
			expect(development.DisplacementMultiplier).to.equal(1.75)
			expect(development.DisplacementAdditive).to.equal(8)
			expect(development.CorrectiveDisplacementMultiplier).to.equal(2.75)
			expect(development.CorrectiveDisplacementAdditive).to.equal(18)
			expect(development.SevereDisplacementMultiplier).to.equal(4)
			expect(development.SevereDisplacementAdditive).to.equal(30)
			expect(development.AccelerationMultiplier).to.equal(4)
			expect(development.AccelerationAdditive).to.equal(40)
			expect(development.UpwardSpeedObservation).to.equal(90)
			expect(development.DownwardSpeedObservation).to.equal(240)
			expect(development.VerticalDisplacementAdditive).to.equal(8)
			expect(development.AngularSpeedMultiplier).to.equal(2.5)
			expect(development.AngularSpeedAdditiveDegrees).to.equal(120)
			expect(development.OwnershipTransitionGrace).to.equal(0.35)
			expect(development.NoDriverAccelerationTolerance).to.equal(100)
			expect(development.ObservationScoreIncrement).to.equal(1)
			expect(development.CorrectiveScoreIncrement).to.equal(2)
			expect(development.SevereScoreIncrement).to.equal(8)
			expect(development.ValidSampleDecay).to.equal(1)
			expect(development.CorrectiveScoreThreshold).to.equal(4)
			expect(development.SevereScoreThreshold).to.equal(8)
			expect(development.MaximumViolationScore).to.equal(12)
			expect(development.CorrectionCooldown).to.equal(1.5)
			expect(development.RepeatedWarningThreshold).to.equal(3)
			expect(development.WarningWindow).to.equal(30)
			expect(development.DiagnosticsEnabled).to.equal(false)
		end)

		it("separates the hard system-safety ceilings from Development tuning", function()
			local safety = CartMovementValidation.SystemSafety

			expect(safety.MaximumHorizontalSpeed).to.equal(220)
			expect(safety.MaximumUpwardSpeed).to.equal(180)
			expect(safety.MaximumDownwardSpeed).to.equal(350)
			expect(safety.MaximumAngularSpeedDegrees).to.equal(1080)
			expect(safety.MaximumVerticalDisplacementAdditive).to.equal(25)
		end)

		it("freezes the complete configuration and both nested sections", function()
			expect(table.isfrozen(CartMovementValidation)).to.equal(true)
			expect(table.isfrozen(CartMovementValidation.Development)).to.equal(true)
			expect(table.isfrozen(CartMovementValidation.SystemSafety)).to.equal(true)
		end)
	end)
end
