--!strict
return function()
	local Shared = game:GetService("ReplicatedStorage").Shared
	local Quality = require(Shared.Utility.ResolvedPresentationQuality)
	local Adaptive = require(Shared.Utility.AdaptiveVFXPolicy)
	describe("effective presentation tier owns platform detail budget", function()
		it("uses conservative Low24 before Auto publisher readiness", function()
			local state = Quality.new()
			expect(state.GetPlatformDetailCap("Auto")).to.equal(24)
			expect(state.GetPlatformDetailCap(nil)).to.equal(24)
		end)
		it("preserves manual preferences while no publisher runs", function()
			local state = Quality.new()
			expect(state.GetPlatformDetailCap("Low")).to.equal(24)
			expect(state.GetPlatformDetailCap("Medium")).to.equal(48)
			expect(state.GetPlatformDetailCap("High")).to.equal(48)
		end)
		it("routes actual Auto effectiveLow to24 despite raw Auto or stale High", function()
			local policy, state = Adaptive.new(), Quality.new()
			policy.Step(0, { mode = "Auto", ready = true, focused = nil })
			local owner = state.Begin(policy.GetTier())
			expect(state.Publish(owner, policy.GetTier())).to.equal(true)
			expect(state.GetPlatformDetailCap("Auto")).to.equal(24)
			expect(state.GetPlatformDetailCap("High")).to.equal(24)
		end)
		it("keeps explicit manual High override of graphicsLow through the real policy", function()
			local policy, state = Adaptive.new(), Quality.new()
			local owner = state.Begin(policy.GetTier())
			policy.Step(0, { mode = "High", savedQuality = 1, ready = true, focused = nil })
			expect(policy.GetTier()).to.equal("High")
			state.Publish(owner, policy.GetTier())
			expect(state.GetPlatformDetailCap("Low")).to.equal(48)
		end)
		it("tracks the same real policy back to Auto graphicsLow", function()
			local policy, state = Adaptive.new(), Quality.new()
			local owner = state.Begin(policy.GetTier())
			policy.Step(0, { mode = "High", savedQuality = 1, ready = true, focused = nil })
			state.Publish(owner, policy.GetTier())
			policy.Step(1, { mode = "Auto", savedQuality = 1, ready = true, focused = nil })
			state.Publish(owner, policy.GetTier())
			expect(state.GetPlatformDetailCap("High")).to.equal(24)
		end)
		it("rejects stale publication and Stop after presenter replacement", function()
			local state = Quality.new()
			local old = state.Begin("High")
			local current = state.Begin("Low")
			expect(state.Publish(old, "High")).to.equal(false)
			expect(state.Release(old)).to.equal(false)
			expect(state.GetPlatformDetailCap("High")).to.equal(24)
			expect(state.Publish(current, "Medium")).to.equal(true)
			expect(state.GetPlatformDetailCap("Low")).to.equal(48)
		end)
		it("release restores only fallback semantics and owns no jobs or listeners", function()
			local state = Quality.new()
			local owner = state.Begin("High")
			expect(state.Release(owner)).to.equal(true)
			expect(state.GetPlatformDetailCap("Auto")).to.equal(24)
			expect(state.GetPlatformDetailCap("High")).to.equal(48)
			local facts = state.GetDiagnostics("Auto")
			expect(facts.publisherActive).to.equal(false)
			expect(facts.ownedConnections).to.equal(0)
			expect(facts.ownedJobs).to.equal(0)
		end)
		it("rejects invalid tiers and no-op refreshes do not accumulate revisions", function()
			local state = Quality.new()
			local owner = state.Begin("Low")
			local revision = state.GetDiagnostics(nil).revision
			for _ = 1, 100 do state.Publish(owner, "Low") end
			expect(state.GetDiagnostics(nil).revision).to.equal(revision)
			expect(state.Publish(owner, "Auto")).to.equal(false)
			expect(state.GetPlatformDetailCap("High")).to.equal(24)
		end)
	end)
end
