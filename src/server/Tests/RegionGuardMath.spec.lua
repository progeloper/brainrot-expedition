--!nocheck
return function()
	local Guard=require(game.ReplicatedStorage.Shared.Utility.RegionGuardMath)
	it("removes only inward motion while preserving parallel, outward and vertical motion",function()
		local normal=Vector3.new(-1,0,0)
		expect(Guard.RemoveInwardVelocity(Vector3.new(-30,4,8),normal)).to.equal(Vector3.new(0,4,8))
		expect(Guard.RemoveInwardVelocity(Vector3.new(30,4,8),normal)).to.equal(Vector3.new(30,4,8))
		expect(Guard.RemoveInwardVelocity(Vector3.new(0,4,8),normal)).to.equal(Vector3.new(0,4,8))
	end)
	it("predicts the assembly footprint crossing before the next shared guard tick",function()
		local normal=Vector3.new(-1,0,0)
		expect(Guard.WouldCross(Vector3.new(18,0,0),Vector3.new(-30,0,0),Vector3.zero,normal,13.5,.1,2)).to.equal(true)
		expect(Guard.WouldCross(Vector3.new(24,0,0),Vector3.new(-30,0,0),Vector3.zero,normal,13.5,.1,2)).to.equal(false)
		expect(Guard.WouldCross(Vector3.new(18,0,0),Vector3.new(30,0,0),Vector3.zero,normal,13.5,.1,2)).to.equal(false)
	end)
	it("uses oriented cart bounds rather than a constant cart radius",function()
		local frame=CFrame.lookAt(Vector3.zero,Vector3.new(-1,0,0))
		expect(Guard.ProjectedHalfExtent(frame,Vector3.new(16,11,28),Vector3.new(-1,0,0))).to.equal(14)
		expect(Guard.ProjectedHalfExtent(frame,Vector3.new(16,11,28),Vector3.new(0,0,1))).to.equal(8)
	end)
	it("rejects invalid gate normals without changing movement",function()
		expect(Guard.IsValidNormal(Vector3.new(1,0,1))).to.equal(false)
		expect(Guard.IsValidNormal(Vector3.new(0,1,0))).to.equal(false)
		expect(Guard.IsValidNormal(Vector3.zero)).to.equal(false)
		expect(Guard.RemoveInwardVelocity(Vector3.new(1,2,3),Vector3.zero)).to.equal(Vector3.new(1,2,3))
	end)
end
