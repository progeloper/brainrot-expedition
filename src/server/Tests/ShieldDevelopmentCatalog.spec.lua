--!strict
return function()
	local RS=game:GetService("ReplicatedStorage")
	local Catalog=require(RS.Shared.Config.BrainrotCatalog)
	local Rules=require(RS.Shared.Utility.ChariotTeamRules)
	local function withFixture(callback)
		local previous=RS:GetAttribute("ShieldDevelopmentFixturesEnabled")
		RS:SetAttribute("ShieldDevelopmentFixturesEnabled",true)
		local definition=table.clone(Catalog.Get("BRT_001"))
		definition.id="FIXTURE_SHIELD_CATALOG"
		definition.displayName="Development Shield fixture"
		definition.developmentFixture=true
		definition.spawnEnabled=false
		definition.chariotEffect={effect="Shield",contribution=1,contributors=2}
		local ok,result=pcall(function()
			Catalog.RegisterDevelopmentFixtures({definition})
			return callback(definition)
		end)
		Catalog.ClearDevelopmentFixtures()
		RS:SetAttribute("ShieldDevelopmentFixturesEnabled",previous)
		assert(ok,result)
		return result
	end
	describe("Transient Shield catalogue fixtures",function()
		it("exercises definition-driven equipment without changing the release roster or spawn declarations",function()
			local result=withFixture(function(definition)
				local entries={}
				for i=1,2 do entries[tostring(i)]={individualId="fixture_owned_"..i,speciesId=definition.id,definition=Catalog.Get(definition.id)}end
				local validId=Catalog.ResolveId(definition.id)
				local resolved,definitionReason=Catalog.GetDefinition(definition.id)
				local rate,rateReason=Catalog.GetCashPerSecond(definition.id)
				return {count=#Catalog.GetAll(),resolved=validId,spawns=Catalog.IsDeclaredSpawnEnabled(definition.id),capacity=Rules.Calculate(entries).shieldCapacity,
					definition=resolved,definitionReason=definitionReason,rate=rate,rateReason=rateReason,expectedRate=definition.cashPerSecond}
			end)
			expect(result.count).to.equal(35)
			expect(result.resolved).to.equal("FIXTURE_SHIELD_CATALOG")
			expect(result.spawns).to.equal(false)
			expect(result.capacity).to.equal(2)
			expect(result.definition.id).to.equal("FIXTURE_SHIELD_CATALOG")
			expect(result.definitionReason).to.equal(nil)
			expect(result.rate).to.equal(result.expectedRate)
			expect(result.rateReason).to.equal(nil)
			expect(Catalog.Get("FIXTURE_SHIELD_CATALOG")).to.equal(nil)
		end)
		it("disables fixture income and definition helpers when the override is turned off",function()
			withFixture(function(definition)
				local registered=Catalog.Get(definition.id)
				expect(Catalog.GetDefinition(definition.id)).to.equal(registered)
				expect(Catalog.GetById(definition.id)).to.equal(registered)
				expect(Catalog.GetCashPerSecond(definition.id)).to.equal(definition.cashPerSecond)
				RS:SetAttribute("ShieldDevelopmentFixturesEnabled",nil)
				expect(Catalog.ResolveId(definition.id)).to.equal(nil)
				expect(Catalog.Get(definition.id)).to.equal(nil)
				expect(Catalog.GetDefinition(definition.id)).to.equal(nil)
				expect(Catalog.GetById(definition.id)).to.equal(nil)
				expect(Catalog.GetCashPerSecond(definition.id)).to.equal(nil)
				expect(#Catalog.GetAll()).to.equal(35)
				expect(Catalog.Definitions[definition.id]).to.equal(nil)
				RS:SetAttribute("ShieldDevelopmentFixturesEnabled",true)
				expect(Catalog.GetDefinition(definition.id)).to.equal(registered)
				expect(Catalog.GetCashPerSecond(definition.id)).to.equal(definition.cashPerSecond)
			end)
		end)
		it("rejects fixture registration without the explicit Studio override",function()
			local previous=RS:GetAttribute("ShieldDevelopmentFixturesEnabled")
			RS:SetAttribute("ShieldDevelopmentFixturesEnabled",nil)
			local ok=pcall(function()Catalog.RegisterDevelopmentFixtures({})end)
			RS:SetAttribute("ShieldDevelopmentFixturesEnabled",previous)
			expect(ok).to.equal(false)
		end)
		it("rejects a fake release declaration instead of adding a spawnable fixture",function()
			local result=withFixture(function(definition)
				local invalid=table.clone(definition)invalid.spawnEnabled=true
				return pcall(function()Catalog.RegisterDevelopmentFixtures({invalid})end)
			end)
			expect(result).to.equal(false)
		end)
	end)
end
