--!nocheck
return function()
	local Runtime = require(script.Parent.Parent.Utility.CartShieldRuntime)
	local function armed(capacity)
		local state = Runtime.Create(0, "FIXTURE_LIFECYCLE")
		Runtime.Reconcile(state, 0, capacity, true, "FIXTURE_OWN_BASE")
		Runtime.Reconcile(state, 1, capacity, true, nil)
		return state
	end
	describe("Shield reserve and exact five-second timing", function()
		it("starts missing expedition state empty outside a verified refill", function()
			local state = Runtime.Create(0, "FIXTURE_MISSING_STATE")
			Runtime.Reconcile(state, 0, 3, true, nil)
			expect(state.Remaining).to.equal(0)
			expect(state.ProtectionExpiresAt).to.equal(0)
			expect(Runtime.ResolveAttack(state, 10).allowKnockoff).to.equal(true)
		end)
		it("matches every approved timing row and spends exactly one whole charge", function()
			local state = armed(2)
			for _, row in { {10,1,15,true}, {10.1,1,15,false}, {14.999,1,15,false}, {15,0,20,true}, {19.999,0,20,false} } do
				local result = Runtime.ResolveAttack(state, row[1])
				expect(result.protected).to.equal(true)
				expect(result.consumed).to.equal(row[4])
				expect(state.Remaining).to.equal(row[2])
				expect(state.ProtectionExpiresAt).to.equal(row[3])
			end
			expect(Runtime.ResolveAttack(state,20).allowKnockoff).to.equal(true)
			expect(state.Remaining).to.equal(0)
			expect(state.ProtectionExpiresAt).to.equal(0)
		end)
		it("retains earned protection through zero capacity and provider re-equipping", function()
			local state = armed(1)
			Runtime.ResolveAttack(state,10)
			Runtime.Reconcile(state,11,0,true,nil)
			expect(state.Remaining).to.equal(0)
			expect(Runtime.ResolveAttack(state,14.999).protected).to.equal(true)
			Runtime.Reconcile(state,14.999,3,true,nil)
			expect(state.Remaining).to.equal(0)
			expect(state.ProtectionExpiresAt).to.equal(15)
			expect(Runtime.ResolveAttack(state,15).allowKnockoff).to.equal(true)
		end)
		it("clamps capacity outside the base without buying, rearranging or rebuilding charges", function()
			local state = armed(3)
			Runtime.ResolveAttack(state,10)
			Runtime.Reconcile(state,11,1,true,nil)
			expect(state.Remaining).to.equal(1)
			Runtime.Reconcile(state,12,3,true,nil)
			expect(state.Remaining).to.equal(1)
			Runtime.Reconcile(state,13,3,true,nil)
			expect(state.Remaining).to.equal(1)
			expect(state.ProtectionExpiresAt).to.equal(15)
		end)
		it("recognizes initial base occupancy, return and capacity change without dwell or deadline extension", function()
			local state = armed(3)
			Runtime.ResolveAttack(state,10)
			local refill = Runtime.Reconcile(state,11,3,true,"FIXTURE_OWN_BASE")
			expect(refill.refilled).to.equal(true)
			expect(state.Remaining).to.equal(3)
			expect(state.ProtectionExpiresAt).to.equal(15)
			expect(Runtime.Reconcile(state,11.01,3,true,"FIXTURE_OWN_BASE").refilled).to.equal(false)
			Runtime.Reconcile(state,12,1,true,"FIXTURE_OWN_BASE")
			Runtime.Reconcile(state,12.01,3,true,"FIXTURE_OWN_BASE")
			expect(state.Remaining).to.equal(3)
			expect(state.ProtectionExpiresAt).to.equal(15)
		end)
		it("does not recharge in a hunt or pause expiry while time passes", function()
			local state = armed(1)
			Runtime.ResolveAttack(state,10)
			Runtime.Reconcile(state,1000,1,true,nil)
			expect(state.Remaining).to.equal(0)
			expect(state.ProtectionExpiresAt).to.equal(0)
		end)
		it("explicit disable clears protection while preserving the spent reserve across enable", function()
			local state = armed(3)
			Runtime.ResolveAttack(state,10)
			Runtime.Reconcile(state,11,0,false,nil)
			expect(state.Remaining).to.equal(2)
			expect(state.Capacity).to.equal(3)
			expect(state.ProtectionExpiresAt).to.equal(0)
			expect(Runtime.ResolveAttack(state,12).accepted).to.equal(false)
			Runtime.Reconcile(state,13,3,true,nil)
			expect(state.Remaining).to.equal(2)
			expect(state.ProtectionExpiresAt).to.equal(0)
		end)
		it("rejects fractional and malformed capacity rather than rounding charges", function()
			for _, value in { -1, .5, 3.1, 4, 0/0, math.huge } do
				expect(function() Runtime.Reconcile(Runtime.Create(0,"FIXTURE_INVALID"),0,value,true,nil) end).to.throw()
			end
		end)
	end)
end
