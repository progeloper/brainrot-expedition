--!nocheck
-- The wallet readout lives in the HUD (HudScreen); this controller only owns the data status banner.
return function()
	local Controller = require(
		game:GetService("StarterPlayer").StarterPlayerScripts.Client.Controllers.PlayerDataStatusController
	)
	local function fixture(callback)
		Controller.Stop()
		local player = Instance.new("Folder")
		local gui = Instance.new("Folder")
		gui.Parent = player
		Controller.Start({ Player = player, PlayerGui = gui })
		local ok, failure = xpcall(function()
			callback(player, gui.PlayerDataStatusGui.Status)
		end, debug.traceback)
		Controller.Stop()
		expect(gui:FindFirstChild("PlayerDataStatusGui")).to.equal(nil)
		player:Destroy()
		assert(ok, failure)
	end
	describe("Player data status banner", function()
		it("shows loading, slow-save and unavailable messages from the player's attributes", function()
			fixture(function(player, pill)
				expect(pill.Visible).to.equal(true)
				expect(pill.Message.Text).to.equal("Loading your data…")
				player:SetAttribute("PlayerDataStatus", "Ready")
				task.wait()
				expect(pill.Visible).to.equal(false)
				expect(pill.Message.Text).to.equal("")
				player:SetAttribute("PlayerDataSaveWarning", true)
				task.wait()
				expect(pill.Visible).to.equal(true)
				expect(pill.Message.Text).to.equal("Saving is taking longer than usual.")
				player:SetAttribute("PlayerDataStatus", "Failed")
				task.wait()
				expect(pill.Visible).to.equal(true)
				expect(pill.Message.Text).to.equal("Your data session is unavailable. Please rejoin.")
				player:SetAttribute("PlayerDataStatus", "Ready")
				player:SetAttribute("PlayerDataSaveWarning", nil)
				task.wait()
				expect(pill.Visible).to.equal(false)
			end)
		end)
		it("is a Plate pill: ink outline, dark body, readable text, tinted by status", function()
			fixture(function(player, pill)
				expect(pill.BackgroundColor3).to.equal(Color3.fromHex("#2B2D38"))
				expect(pill.UIStroke.Color).to.equal(Color3.fromHex("#1D2133"))
				expect(pill.Message.TextSize >= 14).to.equal(true)
				local loading = pill.Message.TextColor3
				player:SetAttribute("PlayerDataStatus", "Failed")
				task.wait()
				expect(pill.Message.TextColor3).to.equal(Color3.fromHex("#FF6B7A"))
				expect(pill.Tint.BackgroundColor3).to.equal(Color3.fromHex("#FF6B7A"))
				expect(pill.Message.TextColor3 == loading).to.equal(false)
				player:SetAttribute("PlayerDataStatus", "Ready")
				player:SetAttribute("PlayerDataSaveWarning", true)
				task.wait()
				expect(pill.Message.TextColor3).to.equal(Color3.fromHex("#FFD447"))
			end)
		end)
	end)
end
