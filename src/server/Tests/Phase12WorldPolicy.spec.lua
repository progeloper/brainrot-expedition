--!nocheck
return function()
	local World = require(script.Parent.Parent.Services.Phase12WorldService)
	describe("Phase12 timed reset survivor policy", function()
		it("cannot accelerate an ordinary or unauthorized reset boundary", function()
			local before = World:GetCycleSnapshot()
			local allowed = World:_AccelerateIsolatedResetForTesting()
			expect(allowed).to.equal(false)
			local after = World:GetCycleSnapshot()
			expect(after.deadline).to.equal(before.deadline)
			expect(after.cycleId).to.equal(before.cycleId)
		end)
		it("preserves valid cargo for an outside owner while retiring fresh held and returning the cart", function()
			local a = World._TestSurvivorPolicy(false, true, false, true)
			local d = World._TestSurvivorPolicy(false, true, true, true)
			expect(a.Policy).to.equal("A")
			expect(d.Policy).to.equal("D")
			for _, policy in { a, d } do
				expect(policy.ForfeitHeld).to.equal(true)
				expect(policy.ForfeitCargo).to.equal(false)
				expect(policy.KillCharacter).to.equal(true)
				expect(policy.ReturnCart).to.equal(true)
			end
		end)
		it("retires a Camp survivor's held catch while preserving its outside cart cargo", function()
			local c = World._TestSurvivorPolicy(true, true, false, true)
			expect(c.Policy).to.equal("C")
			expect(c.ForfeitHeld).to.equal(true)
			expect(c.ForfeitCargo).to.equal(false)
			expect(c.KillCharacter).to.equal(false)
			expect(c.ReturnCart).to.equal(true)
		end)
		it("keeps committed Camp cargo unbanked, retires its held catch and leaves its cart parked", function()
			local b = World._TestSurvivorPolicy(true, true, true, true)
			expect(b.Policy).to.equal("B")
			expect(b.ForfeitHeld).to.equal(true)
			expect(b.ForfeitCargo).to.equal(false)
			expect(b.KillCharacter).to.equal(false)
			expect(b.ReturnCart).to.equal(false)
		end)
		it("does not treat a missing unready profile/character as an outside hunter", function()
			local h = World._TestSurvivorPolicy(false, true, false, false)
			expect(h.Policy).to.equal("H")
			expect(h.ForfeitHeld).to.equal(false)
			expect(h.ForfeitCargo).to.equal(false)
			expect(h.KillCharacter).to.equal(false)
			expect(h.ReturnCart).to.equal(false)
		end)
	end)
end
