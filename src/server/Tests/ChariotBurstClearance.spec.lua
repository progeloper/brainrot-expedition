--!nocheck
return function()
 local P=require(game.ReplicatedStorage.Shared.Utility.ChariotPresentation)
 describe('Burst formation sweep',function()
  it('checks the boosted target envelope before reaching boosted speed',function()
   local m=P.SweepMotion(Vector3.new(0,0,-36),Vector3.new(0,0,-1),.2,45,true)
   expect(m.Z).to.equal(-9)
  end)
  it('keeps normal sweep tied to actual motion',function()
   expect(math.abs(P.SweepMotion(Vector3.new(0,0,-36),Vector3.new(0,0,-1),.2,45,false).Z+7.2)<.00001).to.equal(true)
  end)
  it('never shortens an already faster physical sweep',function()
   expect(P.SweepMotion(Vector3.new(0,0,-50),Vector3.new(0,0,-1),.2,45,true).Z).to.equal(-10)
  end)
  it('uses the firing direction for a stationary active burst',function()
   expect(P.SweepMotion(Vector3.zero,Vector3.new(0,0,-1),.2,45,true).Z).to.equal(-9)
  end)
 end)
end
