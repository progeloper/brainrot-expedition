--!nocheck
return function()
	local Fixture = require(script.Parent.Support.ShieldHandoffFixture)
	local function fixture(callback)
		local f = Fixture.new()
		local ok, failure = xpcall(function() callback(f) end,debug.traceback)
		f.destroy()
		assert(ok,failure)
	end
	describe("Server-only validated cargo-attack handoff",function()
		it("builds a handoff from authoritative attacker session, cart generation and cargo identity",function()
			fixture(function(f)
				f.setBase(false) f.setTime(10)
				local current = f.context(1)
				local source = { Cart = current.cart, Record = f.cargo().Slot1, Revision = current.cargoRevision }
				local built = f.service:CreateCargoAttackContext(f.attacker,7,source)
				expect(built.attackSequence).to.equal(7)
				expect(built.attackId).to.equal("capture:7")
				expect(built.attackerGeneration).to.equal(2)
				expect(built.cartGeneration).to.equal(1)
				expect(built.cargoItemId).to.equal("FIXTURE_CARGO_A")
				expect(built.cargoSlotId).to.equal("Slot1")
				expect(built.cargoRevision).to.equal(0)
				f.setGeneration(f.attacker,4)
				expect(f.attack(built).code).to.equal("STALE_ATTACKER")
				local rebuilt = f.service:CreateCargoAttackContext(f.attacker,8,source)
				expect(rebuilt.attackerGeneration).to.equal(4)
				f.replaceCart()
				expect(f.service:CreateCargoAttackContext(f.attacker,9,source)).to.equal(nil)
				expect(f.service:CreateCargoAttackContext(f.attacker,0,source)).to.equal(nil)
				expect(f.attack(rebuilt).code).to.equal("STALE_CART_OR_CARGO")
				expect(f.snapshot().remaining).to.equal(2)
				expect(f.commits()).to.equal(0)
			end)
		end)
		it("demonstrates the exact table without touching cargo on any protected event",function()
			local rows = Fixture.Run()
			for index,row in rows do
				expect(row.commits).to.equal(if index==6 then 1 else 0)
				expect(row.state.remaining).to.equal(if index<=3 then 1 else 0)
				expect(row.state.protectedUntil).to.equal(if index<=3 then 15 elseif index<=5 then 20 else 0)
				expect(row.decision.protected).to.equal(index<=5)
			end
		end)
		it("deduplicates authoritative attack IDs and sequences across expiry, cache eviction and cart replacement",function()
			fixture(function(f)
				f.setBase(false) f.setTime(10)
				local original = f.context(1)
				expect(f.attack(original).consumed).to.equal(true)
				local messages = #f.messages
				expect(f.attack(original).accepted).to.equal(false)
				expect(#f.messages).to.equal(messages)
				f.setTime(15)
				expect(f.attack(original).accepted).to.equal(false)
				expect(f.snapshot().remaining).to.equal(1)
				f.replaceCart()
				expect(f.attack(original).accepted).to.equal(false)
				local stale = f.context(2) stale.cart = original.cart stale.cartGeneration = original.cartGeneration
				expect(f.attack(stale).code).to.equal("STALE_CART_OR_CARGO")
				f.setTime(200)
				expect(f.attack(original).code).to.equal("OLD_ATTACK")
				expect(f.commits()).to.equal(0)
			end)
		end)
		it("uses one shared reserve for simultaneous attackers and ignores maximum Hit strength",function()
			fixture(function(f)
				f.setBase(false) f.setTime(10)
				local first = f.context(1) first.hitMultiplier = 5
				expect(f.attack(first).consumed).to.equal(true)
				expect(f.attack(f.context(1,f.second,"FIXTURE_CARGO_B","Slot2")).consumed).to.equal(false)
				expect(f.snapshot().remaining).to.equal(1)
				expect(f.snapshot().protectedUntil).to.equal(15)
				expect(f.cargo().Slot1.ItemId).to.equal("FIXTURE_CARGO_A")
				expect(f.cargo().Slot2.ItemId).to.equal("FIXTURE_CARGO_B")
			end)
		end)
		it("scopes identical shot IDs to distinct authoritative attacker sessions",function()
			fixture(function(f)
				f.setBase(false) f.setTime(10)
				local first,second = f.context(1),f.context(1,f.second,"FIXTURE_CARGO_B","Slot2")
				first.attackId = "FIXTURE_SHARED_SHOT_ID" second.attackId = "FIXTURE_SHARED_SHOT_ID"
				expect(f.attack(first).consumed).to.equal(true)
				local nextResult = f.attack(second)
				expect(nextResult.accepted).to.equal(true)
				expect(nextResult.protected).to.equal(true)
				expect(nextResult.consumed).to.equal(false)
				expect(f.attack(first).code).to.equal("DUPLICATE_ATTACK")
				expect(f.attack(second).code).to.equal("DUPLICATE_ATTACK")
				expect(f.snapshot().remaining).to.equal(1)
				expect(f.snapshot().protectedUntil).to.equal(15)
			end)
		end)
		it("rejects misses, player/carry subjects, own targets, safe areas and stale cargo before spending",function()
			fixture(function(f)
				f.setBase(false) f.setTime(10)
				local context = f.context(1)
				expect(f.attack(context,function() return false,"MISS" end).code).to.equal("MISS")
				context.subject = "CarriedPlayer" expect(f.attack(context).code).to.equal("WRONG_SUBJECT")
				context = f.context(2,f.owner) expect(f.attack(context).code).to.equal("INELIGIBLE_OWNER")
				context = f.context(3) context.cargoItemId = "FIXTURE_STALE" expect(f.attack(context).code).to.equal("STALE_CART_OR_CARGO")
				f.setProtectedArea(true) expect(f.attack(f.context(4)).code).to.equal("PROTECTED_AREA")
				expect(f.snapshot().remaining).to.equal(2)
				expect(f.snapshot().protectedUntil).to.equal(0)
				expect(f.commits()).to.equal(0)
			end)
		end)
		it("rechecks cargo identity immediately after the trusted final validator",function()
			fixture(function(f)
				f.setBase(false) f.setTime(10)
				expect(f.attack(f.context(1),function() f.clearCargo() return true end).code).to.equal("SOURCE_CHANGED")
				expect(f.snapshot().remaining).to.equal(2)
				expect(f.commits()).to.equal(0)
			end)
		end)
		it("rejects an inactive cart that momentarily remains in its owner registry",function()
			fixture(function(f)
				f.setBase(false) f.setTime(10)
				local context = f.context(1)
				local parent = context.cart.Parent
				context.cart.Parent = game:GetService("ServerStorage")
				local result = f.attack(context)
				context.cart.Parent = parent
				expect(result.code).to.equal("STALE_CART_OR_CARGO")
				expect(f.snapshot().remaining).to.equal(2)
				expect(f.snapshot().protectedUntil).to.equal(0)
				expect(f.commits()).to.equal(0)
			end)
		end)
		it("rejects yielding validation and serializes a reentrant handoff before commitment",function()
			fixture(function(f)
				f.setBase(false) f.setTime(10)
				expect(f.attack(f.context(1),function() coroutine.yield() return true end).code).to.equal("CALLBACK_YIELDED")
				expect(f.snapshot().remaining).to.equal(2)
				local inner
				local result = f.attack(f.context(2),function() inner = f.attack(f.context(1,f.second)) return true end)
				expect(inner.code).to.equal("BUSY")
				expect(result.consumed).to.equal(true)
				expect(f.snapshot().remaining).to.equal(1)
			end)
		end)
		it("commits an unprotected knockoff at most once, with no replayed feedback",function()
			fixture(function(f)
				f.setBase(false) f.setCapacity(0) f.setTime(10)
				local context = f.context(1)
				local messages = #f.messages
				expect(f.attack(context).knockoffCommitted).to.equal(true)
				expect(f.cargo().Slot1).to.equal(nil)
				expect(f.attack(context).accepted).to.equal(false)
				expect(f.commits()).to.equal(1)
				expect(#f.messages).to.equal(messages)
			end)
		end)
		it("keeps charges and the original window through empty cargo, loading and cart replacement",function()
			fixture(function(f)
				f.setBase(false) f.setTime(10) f.attack(f.context(1))
				local before = f.snapshot()
				f.clearCargo() f.service:Reconcile(f.owner)
				expect(f.snapshot().remaining).to.equal(before.remaining)
				f.setTime(12) f.addCargo("Slot1","FIXTURE_NEW_CARGO") f.replaceCart()
				expect(f.snapshot().lifecycleId).to.equal(before.lifecycleId)
				expect(f.snapshot().protectedUntil).to.equal(15)
				expect(f.attack(f.context(2)).consumed).to.equal(false)
				expect(f.snapshot().remaining).to.equal(1)
			end)
		end)
		it("refills a loaded or empty cart only on verified own-base occupancy and capacity changes there",function()
			fixture(function(f)
				f.setBase(false) f.setTime(10) f.attack(f.context(1))
				f.setTime(11) f.setBase(true)
				expect(f.snapshot().remaining).to.equal(2)
				expect(f.snapshot().protectedUntil).to.equal(15)
				expect(f.cargo().Slot1 ~= nil and f.cargo().Slot2 ~= nil).to.equal(true)
				local messages = #f.messages f.setBase(true) expect(#f.messages).to.equal(messages)
				f.setCapacity(3) expect(f.snapshot().remaining).to.equal(3)
				f.setBase(false) f.clearCargo() f.setCapacity(0) f.setCapacity(3)
				expect(f.snapshot().remaining).to.equal(0)
				f.setBase(true) expect(f.snapshot().remaining).to.equal(3)
				f.setBase(false) f.addCargo("Slot1","FIXTURE_LATER_CARGO")
				expect(f.snapshot().remaining).to.equal(3)
			end)
		end)
		it("discards only departing owner lifecycle and starts missing rejoin reserve at zero outside the base",function()
			fixture(function(f)
				f.setBase(false) f.setTime(10) f.attack(f.context(1))
				local before = f.snapshot()
				f.service:ForgetPlayer(f.owner) f.setGeneration(f.owner,2) f.service:Reconcile(f.owner)
				expect(f.snapshot().remaining).to.equal(0)
				expect(f.snapshot().protectedUntil).to.equal(0)
				expect(f.snapshot().lifecycleId ~= before.lifecycleId).to.equal(true)
				f.setBase(true) expect(f.snapshot().remaining).to.equal(2)
			end)
		end)
		it("waits for ready restoration and grants no charges merely because loading completes",function()
			fixture(function(f)
				f.setBase(false) f.service:ForgetPlayer(f.owner) f.setReady(false)
				expect(f.service:Reconcile(f.owner)).to.equal(nil)
				expect(f.attack(f.context(1)).code).to.equal("OWNER_NOT_READY")
				expect(f.snapshot()).to.equal(nil)
				f.setReady(true) f.service:Reconcile(f.owner)
				expect(f.snapshot().remaining).to.equal(0)
				expect(f.snapshot().protectedUntil).to.equal(0)
			end)
		end)
		it("preserves spent charges across explicit disable without carrying its old active window",function()
			fixture(function(f)
				f.setBase(false) f.setTime(10) f.attack(f.context(1))
				f.service:Stop()
				expect(f.snapshot().remaining).to.equal(1)
				expect(f.snapshot().protectedUntil).to.equal(0)
				f.service:Start() f.service:Reconcile(f.owner)
				expect(f.snapshot().remaining).to.equal(1)
				expect(f.snapshot().protectedUntil).to.equal(0)
			end)
		end)
		it("passes valid attacks through when Shield is disabled without immunity, replay or charge loss",function()
			fixture(function(f)
				f.setBase(false) f.setTime(10) f.attack(f.context(1))
				f.setTime(11) f.setEnabled(false)
				local messages = #f.messages
				local context = f.context(2)
				local result = f.attack(context)
				expect(result.protected).to.equal(false)
				expect(result.consumed).to.equal(false)
				expect(result.knockoffCommitted).to.equal(true)
				expect(f.snapshot().remaining).to.equal(1)
				expect(f.snapshot().protectedUntil).to.equal(0)
				expect(f.attack(context).code).to.equal("DUPLICATE_ATTACK")
				expect(f.commits()).to.equal(1)
				f.setProtectedArea(true)
				expect(f.attack(f.context(3,f.attacker,"FIXTURE_CARGO_B","Slot2")).code).to.equal("PROTECTED_AREA")
				f.setProtectedArea(false)
				expect(f.attack(f.context(4,f.attacker,"FIXTURE_CARGO_B","Slot2"),function() return false,"MISS" end).code).to.equal("MISS")
				expect(f.commits()).to.equal(1)
				expect(#f.messages).to.equal(messages)
				f.setEnabled(true)
				expect(f.snapshot().remaining).to.equal(1)
				expect(f.snapshot().protectedUntil).to.equal(0)
			end)
		end)
		it("bounds cached attacks while preserving the old-sequence rejection watermark",function()
			fixture(function(f)
				f.setBase(false) f.setTime(10)
				for sequence=1,100 do f.attack(f.context(sequence)) end
				local state = f.service.States[f.owner]
				expect(#state.CacheOrder <= 64).to.equal(true)
				expect(f.attack(f.context(1)).code).to.equal("OLD_ATTACK")
				expect(f.snapshot().remaining).to.equal(1)
			end)
		end)
	end)
end
