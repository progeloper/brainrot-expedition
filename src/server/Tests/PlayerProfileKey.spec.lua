--!nocheck
return function()
	local Key = require(script.Parent.Parent.Utility.PlayerProfileKey)
	it("isolates Studio development fixtures without changing ordinary save keys", function()
		expect(Key.Resolve(42, "player_", nil, true, false)).to.equal("player_42")
		expect(Key.Resolve(42, "player_", "fresh_beach", true, false)).to.equal("phase8_test_fresh_beach_player_42")
	end)
	it("cannot override production or published server profile keys", function()
		expect(Key.Resolve(42, "player_", "fixture", true, true)).to.equal("player_42")
		expect(Key.Resolve(42, "player_", "fixture", false, false)).to.equal("player_42")
	end)
	it("rejects invalid fixture namespaces instead of falling back to a normal save", function()
		for _, namespace in {"", string.rep("x", 49), "a/b", "a b", {}, 1} do
			local key, reason = Key.Resolve(42, "player_", namespace, true, false)
			expect(key).to.equal(nil)
			expect(reason).to.equal("INVALID_STUDIO_PROFILE_NAMESPACE")
		end
	end)
	it("validates the complete DataStore key length before attempting acquisition", function()
		local key, reason = Key.Resolve(10098729613, "player_", "fresh_beach_20261006_a", true, false)
		expect(key).to.equal(nil)
		expect(reason).to.equal("STUDIO_PROFILE_KEY_TOO_LONG")
		expect(Key.Resolve(10098729613, "player_", "beach_1006_a", true, false)).to.equal("phase8_test_beach_1006_a_player_10098729613")
	end)

	it("isolates explicitly allowed Main Studio keys without changing published Main routing", function()
		expect(Key.Resolve(42, "player_", "p14m5", true, true, true)).to.equal("phase8_test_p14m5_player_42")
		expect(Key.Resolve(42, "player_", "p14m5", false, true, true)).to.equal("player_42")
	end)
	it("rejects invalid or overlong Main Studio namespaces without a live-key fallback", function()
		local key, reason = Key.Resolve(42, "player_", "bad/key", true, true, true)
		expect(key).to.equal(nil)
		expect(reason).to.equal("INVALID_STUDIO_PROFILE_NAMESPACE")
		local long, errorCode = Key.Resolve(10098729613, "player_", string.rep("x", 35), true, true, true)
		expect(long).to.equal(nil)
		expect(errorCode).to.equal("STUDIO_PROFILE_KEY_TOO_LONG")
	end)
	it("defaults Studio Play to an isolated key when no namespace is set, never on published servers", function()
		local studioNs = Key.StudioNamespace(nil, true)
		expect(Key.Resolve(10098729613, "player_", studioNs, true, true, true)).to.equal("phase8_test_studio_player_10098729613")
		expect(Key.Resolve(-1, "player_", studioNs, true, true, true)).to.equal("phase8_test_studio_player_-1")
		expect(Key.StudioNamespace(nil, false)).to.equal(nil)
		expect(Key.Resolve(42, "player_", Key.StudioNamespace(nil, false), false, true, true)).to.equal("player_42")
		expect(Key.StudioNamespace("ownerreview", true)).to.equal("ownerreview")
	end)

end
