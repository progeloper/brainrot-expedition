--!nocheck
return function()
 local Rules=require(game.ReplicatedStorage.Shared.Utility.ChariotTeamRules)
 local Config=require(game.ReplicatedStorage.Shared.Config.ChariotTeam)
 local Catalog=require(game.ReplicatedStorage.Shared.Config.BrainrotCatalog)
 local function near(a,b) assert(math.abs(a-b)<1e-9,tostring(a)..' != '..tostring(b)) end
 local function entry(id,species,definition)
  return {individualId=id,speciesId=species,definition=definition or Catalog.Get(species)}
 end
 local fixtureDefinitions={}
 for id,spec in Config.SpeciesEffects do fixtureDefinitions[id]={id=id,tier=spec.rarity,cashPerSecond=spec.workbookCPS} end
 local workbookReferences=Rules.BuildReferences(fixtureDefinitions)
 local function fixture(id,species) return entry(id,species,fixtureDefinitions[Catalog.NormalizeId(species)]) end
 local function calculate(entries) return Rules.Calculate(entries,6,workbookReferences) end
 local function secretCopies(count)
  local entries={} for i=1,count do entries[tostring(i)]=fixture(string.char(96+i),'BRT_035') end return entries
 end
 describe('Phase 9 fixed workbook reference and species effects',function()
  it('imports exactly 35 independent assignments at the expected revision',function()
   local count=0 for _ in Config.SpeciesEffects do count+=1 end
   expect(count).to.equal(35) expect(Config.BalanceRevision).to.equal('P9_SHIELD_20261013')
   expect(Config.Version).to.equal(1) expect(Config.SchemaVersion).to.equal(1)
  end)
  for id,spec in Config.SpeciesEffects do
   it(id..' matches its workbook factor and contribution',function()
    local individual=Rules.Individual(fixtureDefinitions[id],id,workbookReferences)
    expect(individual.valid).to.equal(true) expect(individual.effect).to.equal(spec.effect)
    near(individual.valueFactor,spec.workbookFactor) near(individual.contribution,spec.workbookContribution)
    near(individual.displayValue,spec.workbookContribution+(if spec.effect=='Hit' then 1 else 0))
    expect(individual.contributorsGranted).to.equal(spec.contributors)
   end)
  end
  it('current catalogue uniform denomination scaling keeps all 35 effect fixtures',function()
   for id,spec in Config.SpeciesEffects do
    local def=Catalog.Get(id) near(def.cashPerSecond,spec.workbookCPS*1000000)
    local individual=Rules.Individual(def) near(individual.valueFactor,spec.workbookFactor) near(individual.contribution,spec.workbookContribution)
   end
  end)
  it('uses planned species in fixed anchors without enabling release',function()
   local refs=Rules.BuildReferences()
   expect(refs.valid).to.equal(true) expect(refs.count).to.equal(35)
   expect(refs.ranges.Legendary.count).to.equal(3)
   near(refs.ranges.Legendary.minimum,135*1000000) near(refs.ranges.Legendary.maximum,165*1000000)
   for _,id in {'BRT_033','BRT_034','BRT_035'} do expect(Catalog.Get(id).spawnEnabled).to.equal(false) expect(Catalog.Get(id).launchStatus).to.equal('Teased') end
  end)
  it('ignores later catalogue species outside fixed membership',function()
   local definitions=table.clone(fixtureDefinitions) definitions.BRT_999={tier='Legendary',cashPerSecond=999999}
   local refs=Rules.BuildReferences(definitions) expect(refs.count).to.equal(35) near(refs.ranges.Legendary.maximum,165)
  end)
  it('fails an incomplete rarity reference instead of shifting its anchors',function()
   local definitions=table.clone(fixtureDefinitions) definitions.BRT_033=nil
   local refs=Rules.BuildReferences(definitions) expect(refs.valid).to.equal(false) expect(refs.missing[1]).to.equal('BRT_033')
   local raw=Rules.Individual(definitions.BRT_032,'BRT_032',refs)
   expect(raw.valid).to.equal(false) expect(raw.issue).to.equal('REFERENCE_SET_UNAVAILABLE')
   expect(Rules.Individual(definitions.BRT_001,'BRT_001',refs).valid).to.equal(true)
  end)
  it('reconciles a live relative CPS change using the fixed full rarity',function()
   local definitions=table.clone(fixtureDefinitions)
   definitions.BRT_032=table.clone(definitions.BRT_032) definitions.BRT_032.cashPerSecond=165
   local refs=Rules.BuildReferences(definitions)
   near(Rules.Individual(definitions.BRT_032,'BRT_032',refs).valueFactor,1.05)
   near(Rules.Individual(definitions.BRT_032,'BRT_032',refs).contribution,.0473)
  end)
  it('single-species rarities use factor one',function()
   for _,id in {'BRT_034','BRT_035'} do near(Rules.Individual(fixtureDefinitions[id],id,workbookReferences).valueFactor,1) end
  end)
  it('normal catalogue CPS ignores temporary mutation and training fields',function()
   local def=table.clone(fixtureDefinitions.BRT_027) def.liveCPS=999999 def.mutation='Gold' def.level=99 def.incomeMultiplier=100
   near(Rules.Individual(def,'BRT_027',workbookReferences).contribution,.0322)
  end)
  it('normalizes workbook species IDs while preserving individual IDs',function()
   local stats=calculate({['1']=fixture('Owned-id 009','BRT-009')})
   -- A hyphen alias uses the same catalogue definition as the canonical species.
   local direct=Rules.Calculate({['1']=entry('Owned-id 009','BRT-009')})
   expect(direct.details['1'].speciesId).to.equal('BRT_009') expect(direct.details['1'].individualId).to.equal('Owned-id 009') near(direct.speedBonus,.0105)
   expect(stats.count).to.equal(1)
  end)
  for _,value in {0,-1,math.huge,0/0,'12'} do
   it('invalid normal CPS fails closed: '..tostring(value),function()
    local raw=Rules.Individual({id='BRT_019',tier='Rare',cashPerSecond=value},nil,workbookReferences)
    expect(raw.valid).to.equal(false) near(raw.contribution,0) expect(raw.issue).to.equal('INVALID_BASE_CPS')
   end)
  end
 end)
 describe('Phase 9 contributor ranking and independent aggregation',function()
  it('an empty team has three neutral values and limits of one',function()
   local stats=calculate({}) near(stats.speedBonus,0) near(stats.speedMultiplier,1) near(stats.hitMultiplier,1) near(stats.burstCapacity,0)
   expect(stats.count).to.equal(0) for _,effect in {'Speed','Hit','Burst'} do expect(stats.limits[effect]).to.equal(1) expect(stats.effects[effect].selected).to.equal(0) end
  end)
  it('normally selects only each effect strongest member',function()
   local stats=calculate({fixture('a','BRT_027'),fixture('b','BRT_028'),fixture('c','BRT_026'),fixture('d','BRT_031'),fixture('e','BRT_022'),fixture('f','BRT_029')})
   near(stats.speedBonus,.0335) near(stats.hitMultiplier,2.1875) near(stats.burstCapacity,2.52)
   expect(stats.details['1'].status).to.equal('below_limit') expect(stats.details['2'].status).to.equal('contributing')
   expect(stats.details['4'].status).to.equal('future_hit') expect(stats.details['6'].selected).to.equal(true)
  end)
  it('matches the BRT032 plus BRT027 workbook +7.72 percent Speed fixture',function()
   local stats=calculate({fixture('saturn','BRT_032'),fixture('shark','BRT_027')})
   near(stats.speedBonus,.0772) near(stats.speedMultiplier,1.0772) expect(stats.limits.Speed).to.equal(2)
   expect(stats.limits.Hit).to.equal(1) expect(stats.limits.Burst).to.equal(1)
  end)
  it('Top 2 selects the strongest adjusted Speed values and leaves others visible',function()
   local stats=calculate({fixture('saturn','BRT_032'),fixture('shark','BRT_027'),fixture('spider','BRT_028')})
   near(stats.speedBonus,.0785) expect(stats.count).to.equal(3) expect(stats.details['2'].status).to.equal('below_limit') expect(stats.details['2'].valid).to.equal(true)
  end)
  it('two matching Top 2 traits do not stack or multiply Speed',function()
   local stats=calculate({fixture('a','BRT_032'),fixture('b','BRT_032'),fixture('c','BRT_028')})
   expect(stats.limits.Speed).to.equal(2) near(stats.speedBonus,.0855) expect(stats.details['3'].selected).to.equal(false)
  end)
  it('Burst Top 2 affects only Burst and may contribute itself',function()
   local stats=calculate({fixture('a','BRT_034'),fixture('b','BRT_033'),fixture('c','BRT_029'),fixture('d','BRT_028'),fixture('e','BRT_031')})
   expect(stats.limits.Burst).to.equal(2) near(stats.burstCapacity,6.14)
   expect(stats.details['1'].selected).to.equal(true) expect(stats.details['3'].selected).to.equal(false)
   expect(stats.limits.Speed).to.equal(1) expect(stats.limits.Hit).to.equal(1)
  end)
  it('Hit Top 3 adds the neutral multiplier exactly once',function()
   local stats=calculate({fixture('a','BRT_035'),fixture('b','BRT_031'),fixture('c','BRT_014')})
   expect(stats.limits.Hit).to.equal(3) near(stats.hitMultiplier,4.7125)
   for _,d in stats.details do expect(d.status).to.equal('future_hit') end
  end)
  for _,case in {{1,3},{2,4.8},{3,5}} do
   it(case[1]..' Secret copies produce Hit x'..case[2],function()
    local stats=calculate(secretCopies(case[1])) near(stats.hitMultiplier,case[2])
    expect(stats.effects.Hit.capped).to.equal(case[1]==3)
    if case[1]==3 then expect(stats.details['3'].status).to.equal('capped') near(stats.details['3'].appliedContribution,.2) end
   end)
  end
  it('duplicate penalties happen before cross-species ranking',function()
   local stats=calculate({fixture('first','BRT_028'),fixture('second','BRT_028'),fixture('other','BRT_027'),fixture('amp','BRT_032')})
   near(stats.details['2'].contribution,.0335*.9) expect(stats.details['2'].selected).to.equal(false)
   near(stats.details['3'].contribution,.0322) expect(stats.details['3'].selected).to.equal(false)
   -- Before duplicate penalties the two spiders both outrank the shark. After
   -- penalties the shark ranks third and the second spider ranks fourth.
   expect(stats.details['3'].effectRank).to.equal(3) expect(stats.details['2'].effectRank).to.equal(4)
   expect(stats.details['1'].selected).to.equal(true) expect(stats.details['4'].selected).to.equal(true)
   near(stats.speedBonus,.0785)
  end)
  it('duplicate factors use raw value before stable individual ID',function()
   local low={id='BRT_032',tier='Legendary',cashPerSecond=135}
   local stats=calculate({fixture('a','BRT_032'),entry('z','BRT_032',low)})
   near(stats.details['1'].duplicateFactor,1) near(stats.details['2'].duplicateFactor,.9)
   near(stats.details['2'].rawContribution,.0428)
  end)
  it('stable individual IDs break equal raw and adjusted ties across slot ordering',function()
   local original={fixture('c','BRT_035'),fixture('a','BRT_035'),fixture('b','BRT_035'),fixture('speed','BRT_032'),fixture('burst','BRT_034')}
   local first=calculate(original)
   local reordered={original[5],original[4],original[3],original[2],original[1]}
   local second=calculate(reordered)
   near(first.hitMultiplier,second.hitMultiplier) near(first.speedMultiplier,second.speedMultiplier) near(first.burstCapacity,second.burstCapacity)
   local function byIndividual(stats) local map={} for _,d in stats.details do map[d.individualId]=d end return map end
   local a,b=byIndividual(first),byIndividual(second)
   for id,d in a do near(d.duplicateFactor,b[id].duplicateFactor) expect(d.selected).to.equal(b[id].selected) expect(d.status).to.equal(b[id].status) end
   near(a.a.duplicateFactor,1) near(a.b.duplicateFactor,.9) near(a.c.duplicateFactor,.8)
  end)
  it('equal adjusted different species choose the stable ID instead of slot order',function()
   local stats=calculate({fixture('z','BRT_009'),fixture('a','BRT_004')})
   expect(stats.details['1'].selected).to.equal(false) expect(stats.details['2'].selected).to.equal(true)
  end)
  it('preserves unrounded duplicate contributions and selected sums',function()
   local stats=calculate({fixture('a','BRT_028'),fixture('b','BRT_028'),fixture('c','BRT_032')})
   near(stats.details['2'].contribution,.03015) near(stats.speedBonus,.0785)
  end)
  it('caps each effect independently with isolated future-tuning providers',function()
   local function providers(values) local list={} for i,value in values do list[i]={individualId=tostring(i),contribution=value,selected=false} end return list end
   local lists={Speed=providers({.07,.06,.05}),Hit=providers({2.5,2,1}),Burst=providers({4.5,4,3})}
   local effects,capped=Rules.SelectContributors(lists,{Speed=3,Hit=3,Burst=3})
   expect(capped).to.equal(true) near(effects.Speed.appliedBonus,.10) near(1+effects.Hit.appliedBonus,5) near(effects.Burst.appliedBonus,8)
   expect(lists.Speed[2].status).to.equal('capped') near(lists.Speed[2].appliedContribution,.03)
   expect(lists.Speed[3].selected).to.equal(true) near(lists.Speed[3].appliedContribution,0)
   near(lists.Hit[2].appliedContribution,1.5) near(lists.Burst[2].appliedContribution,3.5)
  end)
  it('a capped Hit team leaves its Speed and Burst bonuses intact',function()
   local entries=secretCopies(3) entries['4']=fixture('speed','BRT_032') entries['5']=fixture('burst','BRT_029')
   local stats=calculate(entries) near(stats.hitMultiplier,5) near(stats.speedBonus,.045) near(stats.burstCapacity,2.52)
   expect(stats.effects.Speed.capped).to.equal(false) expect(stats.effects.Burst.capped).to.equal(false)
  end)
  it('unknown species remain occupied but unavailable and contribute zero',function()
   local stats=calculate({['6']={individualId='missing',speciesId='BRT_999'}})
   expect(stats.count).to.equal(1) expect(stats.unavailable).to.equal(1) expect(stats.details['6'].status).to.equal('unavailable') near(stats.hitMultiplier,1)
  end)
  it('locked assignments do not grant effects or amplifier limits',function()
   local stats=Rules.Calculate({['3']=fixture('locked','BRT_035')},2,workbookReferences)
   expect(stats.details['3'].issue).to.equal('LOCKED_SLOT') expect(stats.limits.Hit).to.equal(1) near(stats.hitMultiplier,1)
  end)
  it('one individual cannot contribute from two slots',function()
   local stats=calculate({fixture('same','BRT_032'),fixture('same','BRT_032')})
   expect(stats.details['2'].issue).to.equal('DUPLICATE_INDIVIDUAL') near(stats.speedBonus,.045) expect(stats.unavailable).to.equal(1)
  end)
  it('atomic replacement preview regroups the whole team without changing current entries',function()
   local entries={['1']=fixture('amp','BRT_032'),['2']=fixture('strong','BRT_028'),['3']=fixture('weak','BRT_027')}
   local current=calculate(entries)
   local proposed=Rules.Preview(entries,1,fixture('burst','BRT_029'),6,workbookReferences)
   near(current.speedBonus,.0785) near(proposed.speedBonus,.0335) near(proposed.burstCapacity,2.52)
   expect(proposed.limits.Speed).to.equal(1) expect(entries['1'].individualId).to.equal('amp')
  end)
  it('allows a deliberate weaker replacement that adds no extra current effect',function()
   local entries={fixture('strong','BRT_028'),fixture('hit','BRT_031')}
   local proposed=Rules.Preview(entries,2,fixture('weak','BRT_001'),6,workbookReferences)
   near(proposed.speedBonus,.0335) expect(proposed.details['2'].status).to.equal('below_limit') expect(proposed.count).to.equal(2)
  end)
  it('contains no obsolete combined power acceleration or reel stats',function()
   local stats=calculate({fixture('a','BRT_032')}) expect(stats.teamPower).to.equal(nil) expect(stats.accelerationMultiplier).to.equal(nil) expect(stats.reelMultiplier).to.equal(nil)
  end)
 end)
 describe('Phase 9 actual passive movement values',function()
  it('uses an unboosted upgrade baseline on every recalculation',function()
   local stats=calculate({fixture('saturn','BRT_032'),fixture('shark','BRT_027')})
   local first=Rules.Effective({speed=36},stats,{speed=150})
   local second=Rules.Effective({speed=36},stats,{speed=150}) near(first.speed,38.7792) near(second.speed,first.speed) near(first.percent.speed,7.72)
  end)
  it('shows only physically applied speed when the movement ceiling clips it',function()
   local stats=calculate({fixture('saturn','BRT_032'),fixture('shark','BRT_027')})
   local actual=Rules.Effective({speed=148},stats,{speed=150}) near(actual.speed,150) near(actual.percent.speed,100*(150/148-1)) expect(actual.clipped.speed).to.equal(true)
  end)
  it('a baseline already at an absolute limit gives no extra applied speed',function()
   local actual=Rules.Effective({speed=160},calculate({fixture('a','BRT_032')}),{speed=150}) near(actual.speed,150) near(actual.percent.speed,0) near(actual.speedRatio,1)
  end)
  it('a zero-speed baseline remains valid and preserves other effect totals',function()
   local actual=Rules.Effective({speed=0},calculate({fixture('a','BRT_035'),fixture('b','BRT_029')})) near(actual.speed,0) near(actual.percent.speed,0) near(actual.hitMultiplier,3) near(actual.burstCapacity,2.52)
  end)
 end)
end
