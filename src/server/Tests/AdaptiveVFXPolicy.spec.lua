--!strict
return function()
	local ReplicatedStorage = game:GetService("ReplicatedStorage")
	local AdaptiveVFXPolicy = require(ReplicatedStorage.Shared.Utility.AdaptiveVFXPolicy)
	local function rig(initial: string?)
		local policy = AdaptiveVFXPolicy.new({ initialAutoTier = initial })
		local r: any = {
			policy = policy,
			clock = 0,
			input = { ready = true, focused = true, mode = "Auto", cpuMs = 5, gpuMs = 5, memoryMb = 1000 },
		}
		policy.Step(0, r.input)
		function r.drive(seconds: number, frameMs: number)
			local finish = r.clock + seconds
			while r.clock < finish - 1e-8 do
				local delta = math.min(frameMs / 1000, finish - r.clock)
				r.clock += delta
				policy.RecordFrame(r.clock, delta)
				policy.Step(r.clock, r.input)
			end
		end
		function r.set(key: string, value: any)
			r.input[key] = value
			policy.Step(r.clock, r.input)
		end
		return r
	end
	describe("Adaptive local VFX real policy / controlled clock", function()
		it("starts unknown/Auto at the verified conservative Low", function()
			local r = rig(nil)
			expect(r.policy.GetTier()).to.equal("Low")
			r.drive(9.9, 100)
			expect(r.policy.GetDiagnostics().sampleCount).to.equal(0)
			expect(r.policy.GetTier()).to.equal("Low")
		end)
		it("excludes loading and ten full seconds after readiness", function()
			local r = rig("High")
			r.set("ready", false)
			r.drive(30, 100)
			expect(r.policy.GetDiagnostics().sampleCount).to.equal(0)
			r.set("ready", true)
			r.drive(9.9, 100)
			expect(r.policy.GetDiagnostics().sampleCount).to.equal(0)
			expect(r.policy.GetTier()).to.equal("High")
		end)
		it("requires three valid sustained evaluations at each downgrade threshold", function()
			local r = rig("High")
			r.drive(16, 45)
			expect(r.policy.GetTier()).to.equal("High")
			r.drive(2, 45)
			expect(r.policy.GetTier()).to.equal("Medium")
			r.drive(5, 45)
			expect(r.policy.GetTier()).to.equal("Low")
			local changes = r.policy.GetDiagnostics().transitions
			expect(changes[1].from).to.equal("High")
			expect(changes[1].to).to.equal("Medium")
			expect(changes[2].to).to.equal("Low")
		end)
		it("moves sustained severe pacing straight from High to Low after two evaluations", function()
			local r = rig("High")
			r.drive(15.5, 80)
			expect(r.policy.GetTier()).to.equal("High")
			r.drive(2, 80)
			expect(r.policy.GetTier()).to.equal("Low")
			local changes = r.policy.GetDiagnostics().transitions
			expect(#changes).to.equal(1)
			expect(changes[1].reason).to.equal("SUSTAINED_SEVERE_FRAME_PACING")
		end)
		it("ignores isolated long-frame spikes instead of treating them as sustained p90", function()
			local r = rig("High")
			r.drive(20, 16)
			for _ = 1, 4 do
				r.drive(0.2, 200)
				r.drive(2, 16)
			end
			expect(r.policy.GetTier()).to.equal("High")
			expect(#r.policy.GetDiagnostics().transitions).to.equal(0)
		end)
		it("requires twenty valid seconds for Low recovery and a separate Medium recovery", function()
			local r = rig(nil)
			r.drive(33, 17)
			expect(r.policy.GetTier()).to.equal("Low")
			r.drive(3, 17)
			expect(r.policy.GetTier()).to.equal("Medium")
			r.drive(17, 17)
			expect(r.policy.GetTier()).to.equal("Medium")
			r.drive(5, 17)
			expect(r.policy.GetTier()).to.equal("High")
		end)
		it("uses asymmetric recovery limits rather than oscillating near a threshold", function()
			local r = rig(nil)
			r.drive(40, 25)
			expect(r.policy.GetTier()).to.equal("Medium")
			r.drive(50, 25)
			expect(r.policy.GetTier()).to.equal("Medium")
		end)
		it("does not upgrade during downgrade cooldown even after an immediately good frame stream", function()
			local r = rig("High")
			r.drive(18, 80)
			expect(r.policy.GetTier()).to.equal("Low")
			r.drive(19, 16)
			expect(r.policy.GetTier()).to.equal("Low")
			r.drive(10, 16)
			expect(r.policy.GetTier()).to.equal("Medium")
		end)
		it("excludes unfocused samples and resets recovery with three seconds to settle", function()
			local r = rig(nil)
			r.drive(32, 16)
			r.set("focused", false)
			r.drive(80, 100)
			expect(r.policy.GetTier()).to.equal("Low")
			expect(r.policy.GetDiagnostics().sampleCount).to.equal(0)
			r.set("focused", true)
			r.drive(2.9, 100)
			expect(r.policy.GetDiagnostics().sampleCount).to.equal(0)
			r.drive(25, 16)
			expect(r.policy.GetTier()).to.equal("Low")
			r.drive(5, 16)
			expect(r.policy.GetTier()).to.equal("Medium")
		end)
		it("treats unknown focus as unavailable instead of guessing from device input", function()
			local r = rig("High")
			r.set("focused", nil)
			r.set("touchEnabled", true)
			r.drive(90, 100)
			expect(r.policy.GetTier()).to.equal("High")
			expect(r.policy.GetDiagnostics().status).to.equal("FOCUS_UNAVAILABLE")
		end)
		it("caps Auto to Low for explicit graphics1–3, but preserves explicit manual High", function()
			local r = rig("High")
			r.set("savedQuality", 3)
			r.drive(80, 16)
			expect(r.policy.GetTier()).to.equal("Low")
			r.set("mode", "High")
			r.drive(80, 100)
			expect(r.policy.GetTier()).to.equal("High")
			r.set("mode", "Auto")
			expect(r.policy.GetTier()).to.equal("Low")
		end)
		it("does not classify Automatic0 or unavailable graphics as weak hardware", function()
			local r = rig("High")
			r.set("savedQuality", 0)
			r.drive(20, 16)
			expect(r.policy.GetTier()).to.equal("High")
			expect(r.policy.GetDiagnostics().graphicsCeiling).to.equal("High")
			r.set("savedQuality", nil)
			expect(r.policy.GetDiagnostics().savedQuality).to.equal(nil)
		end)
		it("resets the graphics-change window and cannot upgrade using old samples", function()
			local r = rig(nil)
			r.set("savedQuality", 1)
			r.drive(60, 16)
			r.set("savedQuality", 10)
			r.drive(26, 16)
			expect(r.policy.GetTier()).to.equal("Low")
			r.drive(5, 16)
			expect(r.policy.GetTier()).to.equal("Medium")
		end)
		it("continues deterministic pacing adaptation when busy Stats are missing", function()
			local r = rig("High")
			r.set("cpuMs", nil)
			r.set("gpuMs", nil)
			r.drive(24, 45)
			expect(r.policy.GetTier()).to.equal("Low")
			expect(r.policy.GetDiagnostics().pacingClass).to.equal("BusyTimingsUnavailable")
		end)
		it("does not treat missing rendered callbacks as valid recovery time", function()
			local r = rig(nil)
			r.drive(32, 16)
			r.clock += 100
			r.policy.Step(r.clock, r.input)
			expect(r.policy.GetTier()).to.equal("Low")
			expect(r.policy.GetDiagnostics().recoverySeconds).to.equal(0)
			r.drive(10, 16)
			expect(r.policy.GetTier()).to.equal("Low")
		end)
		it("rejects invalid frame durations and fresh-window trains again", function()
			local r = rig(nil)
			r.drive(31, 16)
			expect(r.policy.RecordFrame(r.clock + 0.01, 0 / 0)).to.equal(false)
			expect(r.policy.GetDiagnostics().sampleCount).to.equal(0)
			r.drive(5, 16)
			expect(r.policy.GetTier()).to.equal("Low")
		end)
		it("evaluates at most once per second despite repeated frame/controller calls", function()
			local r = rig("High")
			r.drive(40, 16)
			local count = r.policy.GetDiagnostics().evaluations
			for _ = 1, 1000 do
				r.policy.Step(r.clock, r.input)
			end
			expect(r.policy.GetDiagnostics().evaluations).to.equal(count)
			expect(count <= 31).to.equal(true)
		end)
		it("avoids tier drops for30-FPS cap/wait-like pacing with supported low busy measurements", function()
			local r = rig("High")
			r.set("cpuMs", 3)
			r.set("gpuMs", 4)
			r.drive(60, 1000 / 30)
			expect(r.policy.GetTier()).to.equal("High")
			expect(r.policy.GetDiagnostics().pacingClass).to.equal("CapOrWaitLikely")
		end)
		it("holds60-FPS cap/wait-like pacing without claiming a measured cap setting", function()
			local r = rig("High")
			r.set("cpuMs", 3)
			r.set("gpuMs", 4)
			r.drive(45, 1000 / 60)
			expect(r.policy.GetTier()).to.equal("High")
			expect(r.policy.GetDiagnostics().pacingClass).to.equal("CapOrWaitLikely")
		end)
		it("does reduce optional High when30-FPS pacing is accompanied by high observed render busy time", function()
			local r = rig("High")
			r.set("cpuMs", 29)
			r.set("gpuMs", 27)
			r.drive(40, 1000 / 30)
			expect(r.policy.GetTier()).to.equal("Medium")
			expect(r.policy.GetDiagnostics().pacingClass).to.equal("BusyTimingsObserved")
			expect(#r.policy.GetDiagnostics().transitions).to.equal(1)
		end)
		it("stays at the floor without repeated downgrade records on a failing~67ms baseline", function()
			local r = rig(nil)
			r.drive(80, 67)
			expect(r.policy.GetTier()).to.equal("Low")
			expect(#r.policy.GetDiagnostics().transitions).to.equal(0)
		end)
		it("does not grant cooldown or recovery seconds across loading/focus exclusions", function()
			local r = rig("High")
			r.drive(18, 80)
			r.set("focused", false)
			r.drive(60, 16)
			expect(r.policy.GetDiagnostics().validSinceDowngrade < 20).to.equal(true)
			r.set("focused", true)
			r.drive(26, 16)
			expect(r.policy.GetTier()).to.equal("Low")
		end)
		it("keeps memory as a measured trend, never a hardware RAM tier guess", function()
			local r = rig("High")
			r.drive(20, 16)
			r.set("memoryMb", 7000)
			r.drive(2, 16)
			expect(r.policy.GetTier()).to.equal("High")
			expect(r.policy.GetDiagnostics().memoryDeltaMb).to.equal(6000)
		end)
		it("bounds samples and returns detached diagnostic transition records", function()
			local r = rig("High")
			r.drive(20, 80)
			local first = r.policy.GetDiagnostics()
			first.transitions[1].reason = "POISON"
			expect(r.policy.GetDiagnostics().transitions[1].reason == "POISON").to.equal(false)
			r.drive(30, 2)
			local d = r.policy.GetDiagnostics()
			expect(d.sampleCount <= d.maxSamples).to.equal(true)
			expect(d.effectiveTier ~= nil).to.equal(true)
		end)
		it("rejects non-finite/zero busy Stats rather than manufacturing a cap explanation", function()
			local r = rig("High")
			r.set("cpuMs", 0 / 0)
			r.set("gpuMs", 0)
			r.drive(22, 1000 / 30)
			expect(r.policy.GetTier()).to.equal("Medium")
			expect(r.policy.GetDiagnostics().pacingClass).to.equal("BusyTimingsUnavailable")
			expect(r.policy.GetDiagnostics().cpuMs).to.equal(nil)
			expect(r.policy.GetDiagnostics().gpuMs).to.equal(nil)
		end)
		it("does not diagnose cap/wait from one low busy snapshot after sustained busy work", function()
			local r = rig("High")
			r.set("cpuMs", 28)
			r.set("gpuMs", 25)
			r.drive(16, 1000 / 30)
			r.set("cpuMs", 3)
			r.set("gpuMs", 4)
			r.drive(2, 1000 / 30)
			expect(r.policy.GetTier()).to.equal("Medium")
			expect(r.policy.GetDiagnostics().pacingClass).to.equal("BusyTimingsObserved")
		end)
		it("clears old observations after a clock regression instead of catching up elapsed time", function()
			local r = rig(nil)
			r.drive(32, 16)
			r.clock = 2
			r.policy.Step(r.clock, r.input)
			expect(r.policy.GetDiagnostics().sampleCount).to.equal(0)
			r.drive(9, 16)
			expect(r.policy.GetTier()).to.equal("Low")
		end)
		it("bounds the transition log through repeated real ceiling/recovery decisions", function()
			local r = rig("High")
			for _ = 1, 12 do
				r.set("savedQuality", 1)
				r.drive(1, 16)
				r.set("savedQuality", 10)
				r.drive(65, 16)
				expect(r.policy.GetTier()).to.equal("High")
			end
			local d = r.policy.GetDiagnostics()
			expect(#d.transitions).to.equal(d.maxTransitions)
			expect(d.sampleCount <= d.maxSamples).to.equal(true)
		end)
	end)
end
