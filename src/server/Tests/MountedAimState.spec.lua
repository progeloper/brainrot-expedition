--!strict

return function()
	local client = game:GetService("StarterPlayer").StarterPlayerScripts.Client
	local State = require(client.State.MountedAimState)
	local Registry = require(game:GetService("ReplicatedStorage").Shared.Config.CartInputRegistry)

	describe("Mounted aiming intent", function()
		it("requires a seat context and preserves independent held input sources", function()
			local state = State.new()
			local cart = Instance.new("Model")
			state.SetRequested("Mouse", true)
			expect(state.IsRequested()).to.equal(false)
			state.SetContext(cart)
			state.SetRequested("Mouse", true)
			state.SetRequested("Touch", true)
			state.SetRequested("Mouse", false)
			expect(state.IsRequested()).to.equal(true)
			state.SetRequested("Touch", false)
			expect(state.IsRequested()).to.equal(false)
			state.Destroy()
			cart:Destroy()
		end)

		it("keeps aim stable on the same cart and clears it when the seat context changes", function()
			local state = State.new()
			local first, second = Instance.new("Model"), Instance.new("Model")
			state.SetContext(first)
			state.SetRequested("Mouse", true)
			state.SetActive(first, true)
			state.SetContext(first)
			expect(state.IsRequested()).to.equal(true)
			expect(state.IsActive(first)).to.equal(true)
			state.AddPointerDelta(Vector2.new(8, 4))
			state.SetGamepadLook(Vector2.new(0.5, -0.5))
			state.SetContext(second)
			expect(state.GetCart()).to.equal(second)
			expect(state.IsRequested()).to.equal(false)
			expect(state.IsActive()).to.equal(false)
			expect(state.ConsumePointerDelta()).to.equal(Vector2.zero)
			expect(state.GetGamepadLook()).to.equal(Vector2.zero)
			state.Destroy()
			first:Destroy()
			second:Destroy()
		end)

		it("rejects activation and stale release for another cart", function()
			local state = State.new()
			local first, second = Instance.new("Model"), Instance.new("Model")
			state.SetContext(first)
			state.SetActive(second, true)
			expect(state.IsActive()).to.equal(false)
			state.SetActive(first, true)
			state.SetActive(second, false)
			expect(state.IsActive(first)).to.equal(true)
			expect(state.IsActive(second)).to.equal(false)
			state.SetActive(nil, false)
			expect(state.IsActive()).to.equal(false)
			state.Destroy()
			first:Destroy()
			second:Destroy()
		end)

		it("accumulates pointer deltas once without publishing camera-frame events", function()
			local state = State.new()
			local cart = Instance.new("Model")
			local changes = 0
			local connection = state.Changed:Connect(function()
				changes += 1
			end)
			state.SetContext(cart)
			state.SetRequested("Mouse", true)
			state.SetActive(cart, true)
			local before = changes
			state.AddPointerDelta(Vector2.new(10, -3))
			state.AddPointerDelta(Vector2.new(-2, 5))
			state.SetGamepadLook(Vector2.new(0.4, 0.7))
			expect(state.ConsumePointerDelta()).to.equal(Vector2.new(8, 2))
			expect(state.ConsumePointerDelta()).to.equal(Vector2.zero)
			expect(state.GetGamepadLook()).to.equal(Vector2.new(0.4, 0.7))
			expect(changes).to.equal(before)
			state.ClearRequested()
			expect(state.IsRequested()).to.equal(false)
			expect(state.GetGamepadLook()).to.equal(Vector2.zero)
			connection:Disconnect()
			state.Destroy()
			cart:Destroy()
		end)

		it("discards look input outside the mounted context", function()
			local state = State.new()
			state.AddPointerDelta(Vector2.new(20, 30))
			state.SetGamepadLook(Vector2.one)
			expect(state.ConsumePointerDelta()).to.equal(Vector2.zero)
			expect(state.GetGamepadLook()).to.equal(Vector2.zero)
			state.Destroy()
		end)

		it("assigns held Aim without changing brake fire or Burst bindings", function()
			expect(Registry.Aim.Mouse).to.equal(Enum.UserInputType.MouseButton2)
			expect(Registry.Aim.Gamepad).to.equal(Enum.KeyCode.ButtonL1)
			expect(Registry.Brake.Gamepad).to.equal(Enum.KeyCode.ButtonL2)
			expect(Registry.Fire.Gamepad).to.equal(Enum.KeyCode.ButtonR2)
			expect(Registry.Fire.Keyboard).to.equal(Enum.KeyCode.G)
			expect(Registry.Burst.Gamepad).to.equal(Enum.KeyCode.ButtonL3)
		end)
	end)
end
