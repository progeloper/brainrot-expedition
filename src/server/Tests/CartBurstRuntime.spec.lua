--!strict

return function()
	local Runtime = require(script.Parent.Parent.Utility.CartBurstRuntime)
	local Requests = require(script.Parent.Parent.Utility.CartBurstRequestState)
	local function close(actual: number, expected: number)
		expect(math.abs(actual - expected) < 1e-7).to.equal(true)
	end
	local function charged(capacity: number, energy: number): any
		local state = Runtime.Create(100)
		Runtime.Step(state, 100, capacity, true, false)
		Runtime.Step(state, 100 + energy * 2, capacity, true, false)
		return state
	end

	describe("Driver Burst elapsed-time energy", function()
		it("starts an owner session at zero even with an equipped provider", function()
			local state = Runtime.Create(100)
			Runtime.Step(state, 100, 8, true, false)
			expect(state.Energy).to.equal(0)
			expect(state.Active).to.equal(false)
		end)
		it("requires a provider and at least a quarter boost-second", function()
			local state = Runtime.Create(0)
			expect(select(2, Runtime.Toggle(state, 0, 0, true, false))).to.equal("NO_PROVIDER")
			Runtime.Step(state, 0, 2, true, false)
			expect(select(2, Runtime.Toggle(state, 0.49, 2, true, false))).to.equal("LOW_ENERGY")
			expect(Runtime.Toggle(state, 0.5, 2, true, false)).to.equal(true)
		end)
		it("drains one energy second per elapsed active second", function()
			local state = charged(8, 4)
			expect(Runtime.Toggle(state, 108, 8, true, false)).to.equal(true)
			Runtime.Step(state, 109.75, 8, true, false)
			close(state.Energy, 2.25)
			expect(state.Active).to.equal(true)
		end)
		it("tap again stops and starts the one-second recharge cooldown", function()
			local state = charged(4, 3)
			Runtime.Toggle(state, 106, 4, true, false)
			Runtime.Toggle(state, 107, 4, true, false)
			close(state.Energy, 2)
			expect(state.Active).to.equal(false)
			expect(Runtime.RechargeState(state, 107.5)).to.equal("COOLDOWN")
			Runtime.Step(state, 108, 4, true, false)
			close(state.Energy, 2)
			Runtime.Step(state, 109, 4, true, false)
			close(state.Energy, 2.5)
		end)
		it("emptying requires a new press even after subsequent recharge", function()
			local state = charged(8, 0.25)
			Runtime.Toggle(state, 100.5, 8, true, false)
			Runtime.Step(state, 100.75, 8, true, false)
			expect(state.Active).to.equal(false)
			expect(state.Energy).to.equal(0)
			Runtime.Step(state, 102.25, 8, true, false)
			close(state.Energy, 0.25)
			expect(state.Active).to.equal(false)
			expect(Runtime.Toggle(state, 102.25, 8, true, false)).to.equal(true)
		end)
		it("settles depletion and recharge boundaries correctly in a long frame", function()
			local state = charged(8, 2)
			Runtime.Toggle(state, 104, 8, true, false)
			Runtime.Step(state, 110, 8, true, false)
			expect(state.Active).to.equal(false)
			close(state.RechargeEligibleAt, 107)
			close(state.Energy, 1.5)
		end)
		it("has the same result for one long interval and many short frames", function()
			local a = charged(8, 3)
			local b = charged(8, 3)
			Runtime.Toggle(a, 106, 8, true, false)
			Runtime.Toggle(b, 106, 8, true, false)
			Runtime.Step(a, 112, 8, true, false)
			for i = 1, 360 do Runtime.Step(b, 106 + i / 60, 8, true, false) end
			close(a.Energy, b.Energy)
			close(a.RechargeEligibleAt, b.RechargeEligibleAt)
			expect(a.Active).to.equal(b.Active)
		end)
		for _, reason in { "BRAKING", "INVALID_DRIVER" } do
			it("stops immediately for " .. reason, function()
				local state = charged(8, 2)
				Runtime.Toggle(state, 104, 8, true, false)
				Runtime.Step(state, 104.1, 8, reason ~= "INVALID_DRIVER", reason == "BRAKING")
				expect(state.Active).to.equal(false)
				expect(state.StopReason).to.equal(reason)
				close(state.Energy, 1.9)
			end)
		end
		it("rejects activation while braking or without driver authority", function()
			local state = charged(8, 2)
			expect(select(2, Runtime.Toggle(state, 104, 8, false, false))).to.equal("INVALID_DRIVER")
			expect(select(2, Runtime.Toggle(state, 104, 8, true, true))).to.equal("BRAKING")
			expect(state.Active).to.equal(false)
		end)
		it("clamps capacity shrink and never scales or refills absolute energy", function()
			local state = charged(8, 3)
			Runtime.Step(state, 106, 2, true, false)
			close(state.Energy, 2)
			Runtime.Step(state, 106, 8, true, false)
			close(state.Energy, 2)
		end)
		it("new capacity cannot retroactively recharge at its higher limit", function()
			local state = Runtime.Create(0)
			Runtime.Step(state, 100, 8, true, false)
			expect(state.Energy).to.equal(0)
			Runtime.Step(state, 101, 8, true, false)
			close(state.Energy, 0.5)
		end)
		it("removing the provider empties capacity and re-equipping restores no energy", function()
			local state = charged(8, 3)
			Runtime.Toggle(state, 106, 8, true, false)
			Runtime.Step(state, 106, 0, true, false)
			expect(state.Active).to.equal(false)
			expect(state.Energy).to.equal(0)
			Runtime.Step(state, 106, 8, true, false)
			expect(state.Energy).to.equal(0)
			Runtime.Step(state, 107, 8, true, false)
			expect(state.Energy).to.equal(0)
		end)
		for _, lifecycle in { "TEAM_CHANGE", "SLOT_PURCHASE", "DRIVER_CHANGE", "CART_REPLACEMENT", "DISMOUNT", "DEATH", "RESET" } do
			it("does not refill on " .. lifecycle, function()
				local state = charged(8, 3)
				Runtime.Toggle(state, 106, 8, true, false)
				if lifecycle ~= "TEAM_CHANGE" and lifecycle ~= "SLOT_PURCHASE" then Runtime.Stop(state, 106, lifecycle) end
				Runtime.Step(state, 106, 8, true, false)
				close(state.Energy, 3)
			end)
		end
		it("a rejoined owner starts a new empty state", function()
			local former = charged(8, 8)
			local nextSession = Runtime.Create(former.LastUpdatedAt)
			Runtime.Step(nextSession, former.LastUpdatedAt, 8, true, false)
			expect(nextSession.Energy).to.equal(0)
		end)
		it("does not gain energy from a backwards clock or duplicate timestamp", function()
			local state = charged(8, 2)
			Runtime.Toggle(state, 104, 8, true, false)
			Runtime.Step(state, 103, 8, true, false)
			Runtime.Step(state, 104, 8, true, false)
			close(state.Energy, 2)
		end)
	end)

	describe("Burst request identity", function()
		it("accepts bounded native-cart payloads and rejects client statistics", function()
			local model = Instance.new("Model")
			local request: any = { cart = model, generation = 1, sequence = 1, action = "Toggle" }
			expect(Requests.IsValid(request)).to.equal(true)
			request.energy = 8
			expect(Requests.IsValid(request)).to.equal(false)
			request.energy = nil
			request.sequence = 0 / 0
			expect(Requests.IsValid(request)).to.equal(false)
			model:Destroy()
		end)
		it("a repeated packet cannot toggle or stack a second boost", function()
			local state = charged(8, 2)
			local requests = { Requests = {}, RequestWindows = {} }
			local driver = {}
			local accepted = Requests.Accept(requests, driver, 1, 104)
			if accepted then Runtime.Toggle(state, 104, 8, true, false) end
			accepted = Requests.Accept(requests, driver, 1, 104)
			if accepted then Runtime.Toggle(state, 104, 8, true, false) end
			expect(accepted).to.equal(false)
			expect(state.Active).to.equal(true)
			close(state.Energy, 2)
		end)
		it("deduplicates across cart changes while tracking distinct drivers independently", function()
			local state = { Requests = {}, RequestWindows = {} }
			local owner, guest = {}, {}
			expect(Requests.Accept(state, owner, 10, 0)).to.equal(true)
			expect(Requests.Accept(state, owner, 10, 2)).to.equal(false)
			expect(Requests.Accept(state, guest, 1, 2)).to.equal(true)
			expect(Requests.Accept(state, owner, 11, 2)).to.equal(true)
		end)
		it("rejects reordered older requests and excessive requests", function()
			local state = { Requests = {}, RequestWindows = {} }
			local driver = {}
			expect(Requests.Accept(state, driver, 2, 0)).to.equal(true)
			expect(select(2, Requests.Accept(state, driver, 1, 0))).to.equal("REPEATED_REQUEST")
			for i = 3, 10 do Requests.Accept(state, driver, i, 0) end
			expect(select(2, Requests.Accept(state, driver, 11, 0))).to.equal("RATE_LIMITED")
			expect(Requests.Accept(state, driver, 11, 1)).to.equal(true)
		end)
	end)
end
