-- Canonical bounded offer contexts identify first affordability without arbitrary strings.
local phase13 = require(script.Parent.Phase13)
local weapons = require(script.Parent.Weapons)
local affordabilityContexts = {}
local function offerContext(key)
	affordabilityContexts[key] = true
	configuration.Categories[key] = true
end
for _, definition in weapons.GetAll() do
	offerContext("Weapon:" .. definition.id)
end
for _, definition in phase13.CartRows do
	offerContext("Cart:" .. definition.id)
end
for _, rows in { phase13.ExpansionRows, phase13.DesignRows } do
	for _, definition in rows do
		if not definition.starter then
			offerContext("Rebirth:" .. definition.id)
		end
	end
end
for level = 1, 5 do
	offerContext("Speed:" .. level)
end
for level = 1, 3 do
	offerContext("Cargo:" .. level)
end
for slot = 3, 6 do
	offerContext("Equipped:" .. slot)
end
configuration.AffordabilityContexts = table.freeze(affordabilityContexts)
configuration.EventUnits = table.freeze({
	RebirthRecoveryDuration = "active world-ready seconds",
	AffordabilityReached = "active world-ready seconds at first eligible affordability per canonical offer/session",
	SessionCheckpoint = "category-specific count or bounded band",
	SaveHealth = "category-specific completed attempts/failures/counts or seconds",
})
return table.freeze(configuration)
